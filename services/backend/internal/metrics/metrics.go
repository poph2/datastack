// Package metrics declares the Prometheus instruments shared by the orchestrator and microservices.
package metrics

import (
	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
)

var (
	// OrchestratorTicks counts simulated days the orchestrator has generated.
	OrchestratorTicks = promauto.NewCounter(prometheus.CounterOpts{
		Name: "app_orchestrator_ticks_total",
		Help: "Simulated days generated by the orchestrator.",
	})

	// SimulatedTime is the orchestrator's current simulated epoch timestamp.
	SimulatedTime = promauto.NewGauge(prometheus.GaugeOpts{
		Name: "app_orchestrator_simulated_time_timestamp_seconds",
		Help: "Current simulated time as a Unix timestamp.",
	})

	// CommandsDispatched counts messages the orchestrator sent to each microservice.
	CommandsDispatched = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "app_orchestrator_commands_dispatched_total",
		Help: "Commands dispatched by the orchestrator.",
	}, []string{"target_service", "command_type"})

	// StateCacheSize tracks how many known entities the orchestrator can reference.
	StateCacheSize = promauto.NewGaugeVec(prometheus.GaugeOpts{
		Name: "app_orchestrator_active_state_cache_count",
		Help: "Entities available to the orchestrator for building commands.",
	}, []string{"entity_type"})

	eventsProcessed = promauto.NewCounterVec(prometheus.CounterOpts{
		Name: "app_service_events_processed_total",
		Help: "Commands and events handled by each microservice.",
	}, []string{"service", "status"})
)

// RecordProcessed counts one handled message for a service, labelled by whether it failed.
func RecordProcessed(service string, err error) {
	status := "success"
	if err != nil {
		status = "error"
	}
	eventsProcessed.WithLabelValues(service, status).Inc()
}
